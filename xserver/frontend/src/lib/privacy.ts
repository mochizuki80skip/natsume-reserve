let cache: Promise<boolean> | null = null;
export function usePrivacyPublished(): boolean {
  const [on, setOn] = useState(false);
  useEffect(() => {
    cache ??= fetch('/api/public-privacy').then((r) => r.json()).then((j) => !!j.published).catch(() => false);
    let alive = true;
    void cache.then((v) => { if (alive) setOn(v); });
    return () => { alive = false; };
  }, []);
  return on;
}
