export type PolicyBlock = { t: 'h'; text: string } | { t: 'p'; text: string } | { t: 'ul'; items: string[] };

/** 文章を見出し・段落・箇条書きに分ける（HTML は使わないので、そのまま安全に表示できる） */
export function parsePolicy(body: string): PolicyBlock[] {
  const out: PolicyBlock[] = [];
  for (const raw of body.replace(/\r\n?/g, '\n').split('\n')) {
    const line = raw.trim();
    if (!line) continue;
    if (line.startsWith('## ')) out.push({ t: 'h', text: line.slice(3) });
    else if (line.startsWith('- ')) {
      const last = out[out.length - 1];
      if (last?.t === 'ul') last.items.push(line.slice(2)); else out.push({ t: 'ul', items: [line.slice(2)] });
    } else out.push({ t: 'p', text: line });
  }
  return out;
}

