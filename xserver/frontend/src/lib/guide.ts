/** 本文の文字（太字の印を外して、調べる用に 1 つにまとめる） */
export function guideText(a: GuideArticle): string {
  return [a.title, a.lead, ...(a.steps ?? []).map((s) => s.text), ...(a.tips ?? []), ...(a.qa ?? []).flatMap((x) => [x.q, x.a]), a.words ?? ''].join(' ').replace(/\*\*/g, '');
}

/** 調べる：言葉（スペース区切りはすべてを含む）で記事を探す。タイトルに入っているものを先に */
export function searchGuide(q: string): { a: GuideArticle; snippet: string }[] {
  const words = q.trim().split(/[\s　]+/).filter(Boolean).map((w) => w.toLowerCase());
  if (!words.length) return [];
  const out: { a: GuideArticle; snippet: string; score: number }[] = [];
  for (const a of GUIDE) {
    const text = guideText(a);
    const low = text.toLowerCase();
    if (!words.every((w) => low.includes(w))) continue;
    const i = low.indexOf(words[0]);
    const from = Math.max(0, i - 20);
    const snippet = (from > 0 ? '…' : '') + text.slice(from, from + 70) + (from + 70 < text.length ? '…' : '');
    out.push({ a, snippet, score: words.filter((w) => a.title.toLowerCase().includes(w)).length });
  }
  return out.sort((x, y) => y.score - x.score).map(({ a, snippet }) => ({ a, snippet }));
}
